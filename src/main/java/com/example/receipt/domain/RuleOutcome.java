package com.example.receipt.domain;

/**
 * 하나의 결정론적 검증 규칙을 실행한 결과다.
 * 영수증 전체의 최종 승인·반려를 의미하지 않으며 상태 라우팅을 위한 판단 근거로 사용한다.
 */
public enum RuleOutcome {
    /** 규칙을 적용했고 검사 조건을 통과했다. */
    PASS,

    /** 규칙을 적용했고 문제를 발견했다. 최종 반려가 아니라 사람 검수가 필요하다는 신호다. */
    FAIL,

    /** 검사할 값이 없거나 해당 영수증에 규칙을 적용할 필요가 없어 검사를 수행하지 않았다. */
    NOT_APPLICABLE
}
